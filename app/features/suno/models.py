"""
Validated data models shared by the Suno feature.
"""

from typing import Literal


from pydantic import BaseModel, Field

#


class SongInfo(BaseModel):
    """
    Metadata extracted from a Suno song page.
    """

    id: str
    type: Literal["hook", "song"] = Field(
        default="song",
        description=(
            "mostly it will songs, but for hook shorts video i will "
            "need another logic so i keep like this"
        ),
    )

    title: str = "Suno AI Song"

    artist: str = ""
    artist_username: str = ""

    prompt: str | None = None
    tags: str | None = Field(
        description="This is some generated by suno and shows in style section",
        default=None,
    )

    base_audio_id: str = Field(
        default="",
        description=(
            "This is the main song's id for hook this is "
            "useful else for song the normal id is same as thsi value"
        ),
    )
    audio_url: str | None = Field(
        default=None,
        description="The url of encrypted audio form where i will downlaod the audio",
    )

    image_url: str | None = None
    video_url: str | None = Field(
        description="This is for hook songs",
        default=None,
    )

    # Stats & metadata from Next.js payload 🎵
    duration: str = ""
    duration_in_seconds: int | None = None
    created_date: str = ""
    plays: int | None = None
    likes: int | None = None

    @property
    def song_url_for_browser(self) -> str:
        """
        Open in browser song url
        URL of the original song, including when this is a hook.
        """

        song_id = self.base_audio_id or self.id
        return f"https://suno.com/song/{song_id}"


class ResolvedSunoLink(BaseModel):
    type: Literal["song", "hook"]
    content_id: str = Field(
        description="The large uuid like thing is content id",
    )

    @property
    def full_url(self) -> str:
        """
        From the large song_id this will make the final
        redirected like url here at last
        """
        return f"https://suno.com/{self.type}/{self.content_id}"


class AudioSampleResult(BaseModel):
    """Details of a sample created from a local audio file."""

    sample_path: str
    filename: str
    total_duration: float
    start_sec: float
    duration_sec: float
    actual_sample_duration: float


class SampleDownloadResult(AudioSampleResult):
    """Details of a sample downloaded directly from a Suno song."""

    info: SongInfo
    cover_path: str | None = None
    format: str


class DownloadResult(BaseModel):
    """Details of a completed full-song download."""

    info: SongInfo
    audio_path: str
    format: str
    duration: float
    cover_path: str | None = None
    metadata_path: str | None = None
    m4a_path: str | None = None


class SeparationResult(BaseModel):
    """Details of separated instrumental and vocal audio tracks."""

    instrumental_path: str
    vocals_path: str
    instrumental_filename: str
    vocals_filename: str
    duration: float
    format: Literal["m4a", "mp3", "wav"]
